def main() -> int:
    modules, pkgs = collect()
    print(f"Modules embedded: {len(modules)} "
          f"({sum(len(v) for v in modules.values()):,} bytes source)")
    payload = {"modules": modules, "pkgs": pkgs}
    blob = base64.b64encode(
        zlib.compress(repr(payload).encode("utf-8"), 9)).decode("ascii")
    out = TEMPLATE.format(blob=blob)
    OUT.write_text(out, encoding="utf-8")
    print(f"Written: {OUT} ({OUT.stat().st_size / 1024:.1f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
