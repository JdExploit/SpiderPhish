def _mod_file(name: str) -> str:
    parts = name.split(".")
    if name in _PKGS:
        return os.path.join(BASE_DIR, *parts, "__init__.py")
    return os.path.join(BASE_DIR, *parts) + ".py"


class _EmbedLoader(importlib.abc.Loader):
    def create_module(self, spec):
        return None  # default module creation

    def exec_module(self, module):
        module.__file__ = _mod_file(module.__name__)
        module.__package__ = (module.__name__ if module.__name__ in _PKGS
                              else module.__name__.rpartition(".")[0])
        code = compile(_MODULES[module.__name__], module.__file__, "exec")
        exec(code, module.__dict__)

    def get_source(self, fullname):
        return _MODULES.get(fullname, "")


class _NsLoader(importlib.abc.Loader):
    """Loader for namespace packages (folders without __init__.py)."""

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        module.__path__ = []
        module.__package__ = module.__name__
        module.__file__ = None


class _EmbedFinder(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        if fullname in _IMPLICIT_PKGS:
            return importlib.machinery.ModuleSpec(
                fullname, _NsLoader(), is_package=True)
        if fullname not in _MODULES:
            return None
