"""Builds SpiderPhish.py - the whole toolkit in ONE
standalone Python file (no project folder needed, only pip requirements).

Usage:
    python scripts/build_singlefile.py

Run the result anywhere:
    python "SpiderPhish.py"
"""
from __future__ import annotations

import base64
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
OUT = ROOT / "SpiderPhish.py"


def module_name(p: Path) -> str:
    rel = p.relative_to(APP.parent)          # e.g. app/gui/theme.py
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def collect() -> tuple[dict[str, str], list[str]]:
    modules: dict[str, str] = {}
    pkgs: list[str] = []
    for p in sorted(APP.rglob("*.py")):
        name = module_name(p)
        modules[name] = p.read_text(encoding="utf-8-sig").lstrip("\ufeff")
        if p.name == "__init__.py":
            pkgs.append(name)
    return modules, pkgs


